function pickRandom<T>(arr: T[], usedTexts: Set<string>, getText: (item: T) => string): T {
  const available = arr.filter((item) => !usedTexts.has(getText(item)));
  const pool = available.length > 0 ? available : arr;
  const chosen = pool[Math.floor(Math.random() * pool.length)];
  usedTexts.add(getText(chosen));
  return chosen;
}

export function getMergedPackCards(pack: GamePack): Record<AttributeKey, PackCardItem[]> {
  const fallback = DEFAULT_PACKS[0].cards;
  const result = {} as Record<AttributeKey, PackCardItem[]>;
  const keys: AttributeKey[] = [
    'profession',
    'gender',
    'health',
    'physique',
    'hobby',
    'trait',
    'phobia',
    'inventory',
    'backpack',
    'extra',
    'specialCard',
  ];

  for (const key of keys) {
    const packList = pack.cards?.[key] || [];
    if (packList.length >= 6) {
      result[key] = packList;
    } else {
      // Combine custom pack cards with classic fallback so large lobbies never run out of unique cards
      const existingTexts = new Set(packList.map((c) => c.text));
      const extras = (fallback[key] || []).filter((c) => !existingTexts.has(c.text));
      result[key] = [...packList, ...extras];
    }
  }
  return result;
}

export function generatePlayerAttributes(
  pack: GamePack,
  usedPerCategory?: Record<AttributeKey, Set<string>>
): PlayerAttributes {
  const cardsPool = getMergedPackCards(pack);
  const tracker: Record<AttributeKey, Set<string>> = usedPerCategory || {
    profession: new Set(),
    gender: new Set(),
    health: new Set(),
    physique: new Set(),
    hobby: new Set(),
    trait: new Set(),
    phobia: new Set(),
    inventory: new Set(),
    backpack: new Set(),
    extra: new Set(),
    specialCard: new Set(),
  };

  const buildCard = (key: AttributeKey) => {
    const item = pickRandom(cardsPool[key], tracker[key], (i) => i.text);
    const hasMandatoryAbility = key === 'profession' || key === 'hobby' || key === 'specialCard';
    const defaultAbility =
      hasMandatoryAbility && !item.ability
        ? {
            name: key === 'profession' ? 'Профессиональный навык' : key === 'hobby' ? 'Прикладное мастерство' : 'Тактический ход',
            description: 'Позволяет вскрыть одну случайную характеристику любого игрока за столом.',
            type: 'instant' as const,
            effectType: 'force_reveal' as const,
            used: false,
          }
        : item.ability
        ? {
            ...item.ability,
            used: false,
          }
        : undefined;

    return {
      text: item.text,
      condition: item.condition,
      rarity: item.rarity || 'common',
      revealed: false,
      ...(defaultAbility ? { ability: defaultAbility } : {}),
    };
  };

  return {
    profession: buildCard('profession'),
    gender: buildCard('gender'),
    health: buildCard('health'),
    physique: buildCard('physique'),
    hobby: buildCard('hobby'),
    trait: buildCard('trait'),
    phobia: buildCard('phobia'),
    inventory: buildCard('inventory'),
    backpack: buildCard('backpack'),
    extra: buildCard('extra'),
    specialCard: buildCard('specialCard'),
  };
}

export function drawSingleAttributeCard(
  pack: GamePack,
  key: AttributeKey,
  excludeTexts: string[] = []
) {
  const cardsPool = getMergedPackCards(pack);
  const usedSet = new Set(excludeTexts);
  const item = pickRandom(cardsPool[key], usedSet, (i) => i.text);
  const hasMandatoryAbility = key === 'profession' || key === 'hobby' || key === 'specialCard';
  return {
    text: item.text,
    condition: item.condition,
    rarity: item.rarity || 'common',
    revealed: true,
    ...(item.ability
      ? { ability: { ...item.ability, used: false } }
      : hasMandatoryAbility
      ? {
          ability: {
            name: 'Экспертное применение',
            description: 'Позволяет принудительно вскрыть случайную характеристику выбранного игрока.',
            type: 'instant' as const,
            effectType: 'force_reveal' as const,
            used: false,
          },
        }
      : {}),
  };
}

